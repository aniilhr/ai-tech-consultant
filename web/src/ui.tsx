export function Progress({ value, max }: { value: number; max: number }) {
  return (
    <div className="progress" title={`${value}/${max}`}>
      <span style={{ width: `${Math.min(100, (value / Math.max(max, 1)) * 100)}%` }} />
    </div>
  );
}

